// palette indices: 0 background, 1 text, 2 accent, 3 muted
const PALETTE = [[250, 250, 247], [24, 24, 24], [0, 100, 60], [130, 130, 125]];

export function ogPng(lines) {
  const px = new Uint8Array(W * H); // all 0 = background
  const fill = (x0, y0, w, h, c) => {
    for (let y = Math.max(0, y0); y < Math.min(H, y0 + h); y++) px.fill(c, y * W + Math.max(0, x0), y * W + Math.min(W, x0 + w));
  };
  const text = (s, x, y, scale, color) => {
    let cx = x;
    for (const ch of s.toUpperCase()) {
      const g = GLYPHS[ch] ?? GLYPHS[" "];
      g.forEach((row, r) => [...row].forEach((bit, c) => { if (bit === "1") fill(cx + c * scale, y + r * scale, scale, scale, color); }));
      cx += 6 * scale;
    }
  };
  fill(0, 0, W, 14, 2);
  for (const l of lines) text(l.text, l.x ?? 60, l.y, l.scale, l.color ?? 1);
  fill(60, H - 90, W - 120, 4, 3);

  // 2 bits per pixel, filter byte 0 per row
  const stride = 1 + Math.ceil((W * 2) / 8);
  const raw = Buffer.alloc(stride * H);
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) raw[y * stride + 1 + (x >> 2)] |= px[y * W + x] << (6 - 2 * (x & 3));
  }
  const crcTable = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
  const crc = (buf) => { let c = 0xffffffff; for (const b of buf) c = crcTable[(c ^ b) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
  const chunk = (type, data) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
    const sum = Buffer.alloc(4); sum.writeUInt32BE(crc(body));
    return Buffer.concat([len, body, sum]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(H, 4); ihdr[8] = 2; ihdr[9] = 3; // 2-bit palette
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", ihdr),
    chunk("PLTE", Buffer.from(PALETTE.flat())),
    chunk("IDAT", deflateSync(raw, { level: 0 })), // stored blocks: byte-identical on any zlib
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
